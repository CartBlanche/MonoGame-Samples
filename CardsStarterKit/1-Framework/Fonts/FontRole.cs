namespace CardsFramework
{
    /// <summary>
    /// Identifies which font role is being requested from an IFontProvider.
    /// </summary>
    public enum FontRole
    {
        /// <summary>Large font used for menu titles and menu entries.</summary>
        Menu,

        /// <summary>Standard body / UI font.</summary>
        Regular,

        /// <summary>Bold variant of the body font.</summary>
        Bold
    }
}
